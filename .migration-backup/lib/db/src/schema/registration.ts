import {
  boolean,
  check,
  index,
  integer,
  jsonb,
  numeric,
  pgTable,
  serial,
  text,
  timestamp,
  uniqueIndex,
} from "drizzle-orm/pg-core";
import { sql } from "drizzle-orm";
import { schoolFiles, schoolRecords, schoolUsers } from "./school";

export const registrationPricingRules = pgTable("registration_pricing_rules", {
  id: serial("id").primaryKey(),
  sourceKey: text("source_key").notNull().unique(),
  country: text("country").notNull(),
  languageId: integer("language_id").references(() => schoolRecords.id),
  courseType: text("course_type").notNull(),
  studyMode: text("study_mode"),
  studySystem: text("study_system"),
  weeklySessions: integer("weekly_sessions"),
  totalSessions: integer("total_sessions"),
  amount: numeric("amount", { precision: 12, scale: 2 }),
  currency: text("currency").notNull(),
  unit: text("unit").notNull(),
  duration: text("duration"),
  lessonHours: numeric("lesson_hours", { precision: 5, scale: 2 }),
  needsReview: boolean("needs_review").notNull().default(false),
  reviewNote: text("review_note").notNull().default(""),
  sourceVersion: text("source_version").notNull(),
  sourcePage: integer("source_page").notNull(),
  active: boolean("active").notNull().default(true),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => [
  index("registration_pricing_match").on(t.country, t.languageId, t.courseType, t.active),
  check("registration_pricing_country", sql`${t.country} in ('algeria','outside_algeria')`),
  check("registration_pricing_course_type", sql`${t.courseType} in ('level','conversation','exam')`),
  check("registration_pricing_mode", sql`${t.studyMode} is null or ${t.studyMode} in ('group','individual')`),
  check("registration_pricing_system", sql`${t.studySystem} is null or ${t.studySystem} in ('regular','intensive')`),
  check("registration_pricing_unit", sql`${t.unit} in ('monthly','level','package')`),
  check("registration_pricing_amount", sql`${t.amount} is null or ${t.amount} >= 0`),
]);

export const registrationRequests = pgTable("registration_requests", {
  id: serial("id").primaryKey(),
  requestNo: text("request_no").notNull().unique(),
  idempotencyKey: text("idempotency_key").notNull().unique(),
  userId: text("user_id").references(() => schoolUsers.id, { onDelete: "set null" }),
  studentProfileId: integer("student_profile_id").references(() => schoolRecords.id, { onDelete: "set null" }),
  enrollmentId: integer("enrollment_id").references(() => schoolRecords.id, { onDelete: "set null" }),
  fullName: text("full_name").notNull(),
  phone: text("phone").notNull(),
  email: text("email").notNull(),
  country: text("country").notNull(),
  languageId: integer("language_id").notNull().references(() => schoolRecords.id),
  courseType: text("course_type").notNull(),
  paymentMethod: text("payment_method").notNull(),
  paymentMethodOther: text("payment_method_other"),
  paymentStatus: text("payment_status").notNull().default("awaiting_payment"),
  status: text("status").notNull().default("pending_review"),
  priceRuleId: integer("price_rule_id").references(() => registrationPricingRules.id, { onDelete: "set null" }),
  priceStatus: text("price_status").notNull(),
  quoteSnapshot: jsonb("quote_snapshot").$type<Record<string, unknown>>().notNull(),
  details: jsonb("details").$type<Record<string, unknown>>().notNull(),
  adminNote: text("admin_note").notNull().default(""),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => [
  index("registration_requests_status_created").on(t.status, t.createdAt),
  index("registration_requests_language_course").on(t.languageId, t.courseType, t.status),
  index("registration_requests_phone").on(t.phone),
  index("registration_requests_email").on(t.email),
  check("registration_request_country", sql`${t.country} in ('algeria','outside_algeria')`),
  check("registration_request_course_type", sql`${t.courseType} in ('level','conversation','exam')`),
  check("registration_request_payment_method", sql`${t.paymentMethod} in ('ccp','baridi_mob','edahabia_cib','international_manual','other')`),
  check("registration_request_payment_status", sql`${t.paymentStatus} in ('awaiting_payment','awaiting_verification','verified','rejected')`),
  check("registration_request_status", sql`${t.status} in ('pending_review','accepted','rejected','needs_info')`),
  check("registration_request_price_status", sql`${t.priceStatus} in ('approved','needs_review','admin_approved')`),
]);

export const registrationReceiptUploads = pgTable("registration_receipt_uploads", {
  id: serial("id").primaryKey(),
  requestId: integer("request_id").references(() => registrationRequests.id),
  objectPath: text("object_path").notNull().unique().references(() => schoolFiles.objectPath),
  uploadTokenHash: text("upload_token_hash").notNull().unique(),
  status: text("status").notNull().default("pending"),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
  attachedAt: timestamp("attached_at", { withTimezone: true }),
}, (t) => [
  index("registration_receipt_request").on(t.requestId),
  index("registration_receipt_expiry").on(t.status, t.expiresAt),
  check("registration_receipt_status", sql`${t.status} in ('pending','attached')`),
]);

export const registrationRequestAudit = pgTable("registration_request_audit", {
  id: serial("id").primaryKey(),
  requestId: integer("request_id").notNull().references(() => registrationRequests.id),
  actorUserId: text("actor_user_id").references(() => schoolUsers.id, { onDelete: "set null" }),
  action: text("action").notNull(),
  previousStatus: text("previous_status"),
  nextStatus: text("next_status"),
  previousQuote: jsonb("previous_quote").$type<Record<string, unknown> | null>(),
  nextQuote: jsonb("next_quote").$type<Record<string, unknown> | null>(),
  reason: text("reason").notNull().default(""),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => [
  index("registration_request_audit_request_created").on(t.requestId, t.createdAt),
]);

export const registrationPricingAudit = pgTable("registration_pricing_audit", {
  id: serial("id").primaryKey(),
  pricingRuleId: integer("pricing_rule_id").notNull().references(() => registrationPricingRules.id),
  actorUserId: text("actor_user_id").references(() => schoolUsers.id, { onDelete: "set null" }),
  previousValues: jsonb("previous_values").$type<Record<string, unknown>>().notNull(),
  nextValues: jsonb("next_values").$type<Record<string, unknown>>().notNull(),
  reason: text("reason").notNull(),
  createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
}, (t) => [
  index("registration_pricing_audit_rule_created").on(t.pricingRuleId, t.createdAt),
]);
